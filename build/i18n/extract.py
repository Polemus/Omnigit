#!/usr/bin/env python3
"""Collect every translatable string in the app into a gettext template.

Omnigit's English lives in the source rather than in a catalogue - the msgid *is* the
English - so this walks the code instead of a resource file. It reads Strings.Get,
Strings.Format, Strings.Plural and Strings.Particular out of C#, and {Loc '...'} out of
XAML, and writes src/Omnigit/Resources/Locale/Omnigit.pot.

xgettext understands C# and would do half of this, but it cannot parse Avalonia XAML, and
two tools that must agree on one output file is the thing worth avoiding.

  extract.py                 write the template
  extract.py --check         fail if the committed template is out of date (CI)
  extract.py --pseudo        also write qps-ploc.po, the fake language

The template carries no POT-Creation-Date. A timestamp would make every run differ from
the committed file and turn --check into noise, which is the same reason nothing in this
repo keeps a second copy of the version.
"""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "Omnigit"
LOCALE = SOURCE / "Resources" / "Locale"
TEMPLATE = LOCALE / "Omnigit.pot"
PSEUDO = LOCALE / "qps-ploc.po"

# The catalogue is what the app falls back from, so the template declares English's rule.
PLURAL_FORMS = "nplurals=2; plural=(n != 1);"

HEADER = f"""\
# Omnigit - translation template.
# This file is generated by build/i18n/extract.py; do not edit it by hand.
# The msgid is the English shown in the app, so there is no English catalogue.
#
msgid ""
msgstr ""
"Project-Id-Version: Omnigit\\n"
"Report-Msgid-Bugs-To: https://github.com/Polemus/Omnigit/issues\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Plural-Forms: {PLURAL_FORMS}\\n"
"""

# One C# string literal: "..." with \\-escapes. Verbatim (@"") and raw (\"\"\") literals are
# not matched on purpose - a sentence written in one would be silently skipped, so the
# scan reports any call whose first argument it could not read rather than dropping it.
LITERAL = r'"(?:[^"\\]|\\.)*"'
WS = r"\s*"

# A long sentence is naturally written as "..." + "..." across two lines, and reading only
# the first half would put a msgid in the template that no lookup can ever match - the app
# would ask for the whole sentence and the catalogue would hold half of it. So a run of
# literals joined by + is one string, exactly as the compiler sees it.
JOINED = "(" + LITERAL + "(?:" + WS + r"\+" + WS + LITERAL + ")*)"

CALLS = [
    (re.compile(r"Strings\.Get\(" + WS + JOINED), 1),
    (re.compile(r"Strings\.Format\(" + WS + JOINED), 1),
    (re.compile(r"Strings\.Particular\(" + WS + JOINED + WS + "," + WS + JOINED), 2),
    (re.compile(r"Strings\.Plural\(" + WS + JOINED + WS + "," + WS + JOINED), 2),
]

PIECE = re.compile(LITERAL)


def literal(source: str) -> str:
    """One C# string, or a run of them joined by +, as the compiler would see it."""
    return "".join(unescape(piece[1:-1]) for piece in PIECE.findall(source))

# Any Strings.* call whose arguments this scan did not manage to read.
SUSPECT = re.compile(r"Strings\.(Get|Format|Plural|Particular)\(")

LOC = re.compile(r"\{Loc" + WS + r"'((?:[^'\\]|\\.)*)'" + WS + r"\}")

# The element form, used where a sentence contains an apostrophe or a quote and so cannot
# sit inside the markup extension's own string. Key is an ordinary XML attribute there,
# so XML entities have to be undone - the attribute is the only place &quot; appears.
LOC_ELEMENT = re.compile(r"<Loc\s+Key=\"([^\"]*)\"")

ENTITIES = {"&quot;": '"', "&apos;": "'", "&lt;": "<", "&gt;": ">", "&amp;": "&"}


def unentity(value: str) -> str:
    for entity, character in ENTITIES.items():
        value = value.replace(entity, character)
    return value


class Entry:
    """One msgid, with wherever it was found and its plural if it has one."""

    def __init__(self, text: str) -> None:
        self.text = text
        self.plural: str | None = None
        self.context: str | None = None
        self.references: list[str] = []

    @property
    def key(self) -> tuple[str, str]:
        return (self.context or "", self.text)


def unescape(value: str) -> str:
    """C# source escaping to the real characters, so the .pot holds the actual sentence."""
    out, i = [], 0
    while i < len(value):
        c = value[i]
        if c != "\\" or i + 1 >= len(value):
            out.append(c)
            i += 1
            continue
        nxt = value[i + 1]
        out.append({"n": "\n", "t": "\t", "r": "\r", "0": "\0"}.get(nxt, nxt))
        i += 2
    return "".join(out)


def escape(value: str) -> str:
    out = value.replace("\\", "\\\\").replace('"', '\\"')
    return out.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")


def collect() -> tuple[dict[tuple[str, str], Entry], list[str]]:
    found: dict[tuple[str, str], Entry] = {}
    unreadable: list[str] = []

    def add(text: str, where: str, plural: str | None = None, context: str | None = None) -> None:
        entry = Entry(text)
        entry.context = context
        existing = found.get(entry.key)
        if existing is None:
            found[entry.key] = entry
            existing = entry
        if plural and not existing.plural:
            existing.plural = plural
        if where not in existing.references:
            existing.references.append(where)

    for path in sorted(SOURCE.rglob("*.cs")):
        if any(part in ("obj", "bin") for part in path.parts):
            continue
        # The app's own localization plumbing mentions these method names; so does the
        # design-time sample content, which nothing at runtime reads.
        if path.name in ("Strings.cs", "Localizer.cs", "MockData.cs"):
            continue

        text = path.read_text(encoding="utf-8")
        rel = path.relative_to(ROOT).as_posix()
        seen_spans: list[tuple[int, int]] = []

        for pattern, arity in CALLS:
            for match in pattern.finditer(text):
                line = text.count("\n", 0, match.start()) + 1
                where = f"{rel}:{line}"
                seen_spans.append(match.span())
                one = literal(match.group(1))
                if pattern.pattern.startswith(r"Strings\.Particular"):
                    add(literal(match.group(2)), where, context=one)
                elif arity == 2:
                    add(one, where, plural=literal(match.group(2)))
                else:
                    add(one, where)

        for match in SUSPECT.finditer(text):
            if not any(start <= match.start() < end for start, end in seen_spans):
                line = text.count("\n", 0, match.start()) + 1
                unreadable.append(f"{rel}:{line}")

    for path in sorted(SOURCE.rglob("*.axaml")):
        text = path.read_text(encoding="utf-8")
        rel = path.relative_to(ROOT).as_posix()
        for match in LOC.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            add(unentity(match.group(1).replace("\\'", "'")), f"{rel}:{line}")

        for match in LOC_ELEMENT.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            add(unentity(match.group(1)), f"{rel}:{line}")

    return found, unreadable


def render(entries: dict[tuple[str, str], Entry], translate=None) -> str:
    out = [HEADER.rstrip("\n")]

    for key in sorted(entries):
        entry = entries[key]
        out.append("")
        for reference in entry.references:
            out.append(f"#: {reference}")
        if entry.context:
            out.append(f'msgctxt "{escape(entry.context)}"')
        out.append(f'msgid "{escape(entry.text)}"')

        if entry.plural:
            out.append(f'msgid_plural "{escape(entry.plural)}"')
            forms = [entry.text, entry.plural] if translate is None else [
                translate(entry.text), translate(entry.plural)
            ]
            for index, form in enumerate(forms if translate else ["", ""]):
                out.append(f'msgstr[{index}] "{escape(form)}"')
        else:
            value = translate(entry.text) if translate else ""
            out.append(f'msgstr "{escape(value)}"')

    return "\n".join(out) + "\n"


# ---- the fake language ---------------------------------------------------------------

ACCENTS = {
    "a": "\u00e5", "b": "\u0180", "c": "\u00e7", "d": "\u0111", "e": "\u00e9",
    "f": "\u0192", "g": "\u011f", "h": "\u0125", "i": "\u00ef", "j": "\u0135",
    "k": "\u0137", "l": "\u013c", "m": "\u1e41", "n": "\u00f1", "o": "\u00f6",
    "p": "\u00fe", "q": "\u01eb", "r": "\u0157", "s": "\u0161", "t": "\u0163",
    "u": "\u00fb", "v": "\u1e7d", "w": "\u0175", "x": "\u1e8b", "y": "\u00fd",
    "z": "\u017e",
}

PLACEHOLDER = re.compile(r"\{\d+[^}]*\}")


def pseudo(value: str) -> str:
    """Accent every letter and pad, leaving {0} alone.

    Two bugs show up under this and under nothing else: a string still hardcoded reads as
    plain English on a page of accents, and a control sized to its English text clips as
    soon as the words get longer, which is what German does to every button in the app.
    """
    pieces, at = [], 0
    for hole in PLACEHOLDER.finditer(value):
        pieces.append(("text", value[at:hole.start()]))
        pieces.append(("hole", hole.group(0)))
        at = hole.end()
    pieces.append(("text", value[at:]))

    out = []
    for kind, piece in pieces:
        if kind == "hole":
            out.append(piece)
            continue
        out.append("".join(
            ACCENTS.get(c, ACCENTS.get(c.lower(), c).upper() if c.isupper() else c)
            for c in piece
        ))

    body = "".join(out)
    # ~30% longer, which is about what English to German costs.
    padding = "\u00b7" * max(1, round(len(value) * 0.3))
    return f"[!!{body} {padding}!!]"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed template is out of date")
    args = parser.parse_args()

    entries, unreadable = collect()

    if unreadable:
        for where in unreadable:
            print(f"{where}: a Strings call whose text could not be read - it must be a "
                  f"plain \"literal\", not a variable, a @verbatim or a raw string",
                  file=sys.stderr)
        return 1

    wanted = {
        TEMPLATE: render(entries),
        PSEUDO: render(entries, translate=pseudo).replace(
            f'"Plural-Forms: {PLURAL_FORMS}\\n"',
            f'"Language: qps-ploc\\n"\n"Plural-Forms: {PLURAL_FORMS}\\n"'),
    }

    if args.check:
        stale = [
            path for path, body in wanted.items()
            if (path.read_text(encoding="utf-8") if path.exists() else "") != body
        ]

        if stale:
            for path in stale:
                print(f"{path.relative_to(ROOT)} is out of date", file=sys.stderr)
            print("run build/i18n/extract.py", file=sys.stderr)
            return 1

        print(f"{len(entries)} strings, catalogues up to date")
        return 0

    LOCALE.mkdir(parents=True, exist_ok=True)

    for path, body in wanted.items():
        path.write_text(body, encoding="utf-8")

    print(f"{len(entries)} strings -> {TEMPLATE.name}, {PSEUDO.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
